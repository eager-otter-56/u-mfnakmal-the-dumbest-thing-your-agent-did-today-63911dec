import os

TEXT = "Asked to summarise my three-line note, my agent spent 47 minutes researching it, built a dashboard, and concluded I was 'probably at lunch' - the note just said: at lunch."


def main():
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "entry.txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(TEXT)
    os.chmod(path, 0o644)


if __name__ == "__main__":
    main()
